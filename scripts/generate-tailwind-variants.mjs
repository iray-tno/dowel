// Regenerates `crates/hozo_parser/src/tailwind_variants.rs` from Tailwind.
//
// The denominator for "is this a Tailwind class Hozo failed to compile, or
// just one of the project's own?". Without it those two are the same
// thing: an unrecognised class is carried into the output either way, and
// only one of them deserves to be mentioned.
//
// `group-hover:bg-blue-500` used to compile to nothing, reach the DOM as
// nothing, and say nothing. It is now carried, but carried is not the same
// as working -- nothing defines that class unless the project runs its own
// Tailwind build. This list is how Hozo can tell the author which of those
// they are in.
//
// Generated for the same reason the ARIA table and the conformance
// harness's class list are: a hand-kept copy of somebody else's list
// drifts, and both halves go on looking reasonable while it does.
//
//   node scripts/generate-tailwind-variants.mjs
import { writeFileSync } from 'node:fs'

const { __unstable__loadDesignSystem } = await import('tailwindcss')

const design = await __unstable__loadDesignSystem('@import "tailwindcss";', {
  loadStylesheet: async () => ({ base: '/', content: '@tailwind utilities;' }),
})

// `getVariants()` is the same call the editor tooling makes, so this is
// the list a Tailwind user's completions offer them.
const variants = design.getVariants()
const names = variants.map((variant) => variant.name).sort()

// `aria` is a functional variant with a named-value shortlist -- Tailwind
// spells `aria-checked:` and `aria-[sort=ascending]:` from the same one.
// The shortlist is what Hozo compiles, so it comes from Tailwind too
// rather than from a set of names that looked complete.
const ariaValues = (variants.find((variant) => variant.name === 'aria')?.values ?? []).slice().sort()

writeFileSync(
  'crates/hozo_parser/src/tailwind_variants.rs',
  `// Generated by scripts/generate-tailwind-variants.mjs from tailwindcss. Do not edit.
//
// Every variant name Tailwind defines. Hozo implements a fraction of them,
// and this is what lets it tell the difference between a class it should
// have compiled and one that was never Tailwind's to begin with -- a
// project's own \`my-card\` is not a gap in Hozo, and \`group-hover:\` is.
//
// Names only. What each variant *means* is Tailwind's business and, where
// Hozo implements one, \`tailwind.rs\`'s.

/// Every variant name Tailwind defines, sorted.
pub const TAILWIND_VARIANTS: &[&str] = &[
${names.map((name) => `    ${JSON.stringify(name)},`).join('\n')}
];

/// The states \`aria-…:\` is written with, as Tailwind names them.
///
/// Every one is an ARIA attribute whose value is \`"true"\` or \`"false"\`,
/// which is why a shortlist exists at all: \`aria-sort\` takes four words
/// and has no boolean form, so it is written \`aria-[sort=ascending]:\`.
pub const ARIA_VARIANT_STATES: &[&str] = &[
${ariaValues.map((value) => `    ${JSON.stringify(value)},`).join('\n')}
];

/// Whether \`name\` is a variant Tailwind defines.
///
/// Functional variants (\`aria\`, \`data\`, \`group\`, \`peer\`, \`has\`, \`not\`,
/// \`supports\`, \`min\`, \`max\`) are listed under their bare name and written
/// with a suffix or an argument -- \`aria-checked:\`, \`group-hover:\`. So a
/// prefix is checked whole and then again up to its first dash.
pub fn is_variant(name: &str) -> bool {
    if TAILWIND_VARIANTS.contains(&name) {
        return true;
    }
    match name.split_once('-') {
        Some((head, _)) => TAILWIND_VARIANTS.contains(&head),
        None => false,
    }
}
`,
)
console.log(`wrote ${names.length} Tailwind variants`)
